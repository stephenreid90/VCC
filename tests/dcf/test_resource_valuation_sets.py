"""The committed resource valuation sets are reproduced by committed code (standing rule 4).

``design/methodology/resource_valuation_sets.yaml`` is generated by
``scripts/size_resource_valuation.py``; every number the resource-lifecycle method paper
cites comes from it. This regenerates the sets and requires them to match to the
precision written.
"""

from __future__ import annotations

import importlib.util
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]


def _size():
    spec = importlib.util.spec_from_file_location("size_resource_valuation",
                                                  ROOT / "scripts" / "size_resource_valuation.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod.size()


def test_committed_sets_are_reproduced():
    committed = yaml.safe_load((ROOT / "design" / "methodology" / "resource_valuation_sets.yaml").read_text(encoding="utf-8"))
    assert _size() == committed


def test_exactly_one_set_per_company_is_current():
    committed = yaml.safe_load((ROOT / "design" / "methodology" / "resource_valuation_sets.yaml").read_text(encoding="utf-8"))
    for cid, s in committed["sets"].items():
        assert s["status"] == "current", cid
